func TestResolvedManaged(t *testing.T) {
	cases := []struct {
		name, content string
		want          bool
	}{
		{"Ubuntu 的 stub-resolv.conf", "# This is /run/systemd/resolve/stub-resolv.conf managed by man:systemd-resolved(8).\n# Do not edit.\nnameserver 127.0.0.53\n", true},
		{"NetworkManager 写的", "# Generated by NetworkManager\nnameserver 192.168.1.1\n", false},
		{"手写的", "nameserver 1.1.1.1\n", false},
		// 和 sing-box 的判断一致：注释之前有空行也不算，见 resolvedManaged。
		{"开头是空行", "\n# managed by man:systemd-resolved(8)\n", false},
	}
	for _, c := range cases {
		if got := resolvedManaged([]byte(c.content)); got != c.want {
			t.Errorf("%s: resolvedManaged = %v，想要 %v", c.name, got, c.want)
		}
	}
}

func TestRouteConflictLinux(t *testing.T) {
	cases := []struct {
		name, json string
		taken      bool
	}{
		{"只有默认路由", `[{"dst":"default","gateway":"192.168.1.254","dev":"wlp2s0"}]`, false},
		{"别的 VPN 盖住默认路由的大段", `[{"dst":"0.0.0.0/1","dev":"tun0"},{"dst":"default","dev":"eth0"}]`, false},
		{"别的网卡接管了这个 /24", `[{"dst":"198.51.100.0/24","dev":"wg0"}]`, true},
		{"一条主机路由", `[{"dst":"198.51.100.1","dev":"tailscale0","table":"52"}]`, true},
		{"上次留下的自己的路由", `[{"dst":"198.51.100.0/24","dev":"sidedoor0"}]`, false},
	}
	for _, c := range cases {
		if _, taken := routeConflict([]byte(c.json)); taken != c.taken {
			t.Errorf("%s: 判断为被占 %v，想要 %v", c.name, taken, c.taken)
		}
	}
}

// TestTunLinuxSplitDNS 在真机上跑一遍 tun 模式，验证分流 DNS 和路由只接管走 VPN 的域名：
//
//   - 走 VPN 的域名，应用照常查（经 /etc/resolv.conf 里的 127.0.0.53 问 resolved），拿到假 IP；
//   - VPN 服务器自己的名字也在这个后缀下面，查它不能拿到假 IP，也不能被 resolved 转回来
//     绕圈（那样会一直超时）；
//   - 别的域名照旧问原来的 DNS；ip rule 一条都不加；
//   - 停掉之后网卡、路由、分流 DNS 都没了。
//
// 用的是测试专用的域名，VPN 服务器连不上，不碰真实的学校域名。要 root：
//
//	sudo ./sidedoor-linux-amd64.test -test.run TestTunLinuxSplitDNS -test.v
func TestTunLinuxSplitDNS(t *testing.T) {
	if os.Geteuid() != 0 {
		t.Skip("要 root 才能建网卡，用 sudo 运行")
	}
	if err := tunPreflight(nil); err != nil {
		t.Skipf("这台机器不满足 tun 模式的条件: %v", err)
	}
	if _, err := net.InterfaceByName(tunName); err == nil {
		t.Skip(tunName + " 已经存在，可能有 tun 模式的服务在跑")
	}
	defer func(dir string) { systemConfigDir = dir }(systemConfigDir)
	systemConfigDir = t.TempDir() // 假 IP 的缓存文件不写进 /etc/sidedoor
	rulesBefore := command(t, "ip", "rule", "show")

	const domain = "sidedoor-test.example.com"
	cfg := testConfig(t, ModeTUN)
	cfg.Server = "vpn." + domain + ":1"
	cfg.Domains = []string{domain}
	ctx, cancel := context.WithCancel(context.Background())
	done := make(chan error, 1)
	go func() { done <- runEngine(ctx, cfg, filepath.Join(t.TempDir(), "config.json"), "pw", false) }()
	running := true
	stop := func() {
		if running {
			running = false
			cancel()
			<-done
		}
	}
	defer stop()

	fake := netip.MustParsePrefix(fakeIPRange)
	var addr netip.Addr
	for deadline := time.Now().Add(15 * time.Second); time.Now().Before(deadline); time.Sleep(200 * time.Millisecond) {
		if addrs, err := lookup("www." + domain); err == nil && len(addrs) > 0 {
			addr = addrs[0]
			break
		}
	}
	if !fake.Contains(addr) {
		t.Fatalf("走 VPN 的域名应当解析成假 IP，实际 %v", addr)
	}

	start := time.Now()
	addrs, err := lookup("vpn." + domain)
	var dnsErr *net.DNSError
	switch {
	case err != nil && errors.As(err, &dnsErr) && dnsErr.IsTimeout:
		t.Errorf("查 VPN 服务器的名字超时了（%v），疑似被 resolved 转回自己绕圈", time.Since(start))
	case err == nil && len(addrs) > 0 && fake.Contains(addrs[0]):
		t.Errorf("VPN 服务器的名字不该拿到假 IP，实际 %v", addrs)
	}

	if addrs, err := lookup("example.com"); err != nil || len(addrs) == 0 || fake.Contains(addrs[0]) {
		t.Errorf("别的域名应当照旧解析成真实地址，实际 %v, %v", addrs, err)
	}

	for _, c := range []struct {
		args []string
		want string
	}{
		{[]string{"resolvectl", "dns", tunName}, tunDNS},
		{[]string{"resolvectl", "domain", tunName}, "~" + domain},
		{[]string{"resolvectl", "default-route", tunName}, "no"},
		{[]string{"ip", "-4", "route", "show", fakeIPRange}, "dev " + tunName},
	} {
		if out := command(t, c.args...); !strings.Contains(out, c.want) {
			t.Errorf("%s 里应当有 %q，实际 %q", strings.Join(c.args, " "), c.want, out)
		}
	}
	if rules := command(t, "ip", "rule", "show"); rules != rulesBefore {
		t.Errorf("tun 模式不该加 ip rule：\n之前\n%s\n现在\n%s", rulesBefore, rules)
	}

	stop()
	if _, err := net.InterfaceByName(tunName); err == nil {
		t.Errorf("停掉之后 %s 应当消失", tunName)
	}
	if out := command(t, "ip", "-4", "route", "show", fakeIPRange); strings.TrimSpace(out) != "" {
		t.Errorf("停掉之后假 IP 段的路由应当消失，实际 %q", out)
	}
	if addrs, err := lookup("www." + domain); err == nil && len(addrs) > 0 && fake.Contains(addrs[0]) {
		t.Errorf("停掉之后不该再解析成假 IP，实际 %v", addrs)
	}
}

// lookup 像普通应用那样查一个名字：Go 的解析器读 /etc/resolv.conf，问 127.0.0.53 上的 resolved。
func lookup(name string) ([]netip.Addr, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	return (&net.Resolver{PreferGo: true}).LookupNetIP(ctx, "ip4", name)
}

func command(t *testing.T, args ...string) string {
	t.Helper()
	out, err := exec.Command(args[0], args[1:]...).CombinedOutput()
	if err != nil {
		t.Logf("%s: %v: %s", strings.Join(args, " "), err, out)
	}
	return string(out)
}
